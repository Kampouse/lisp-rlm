#!/usr/bin/env python3
"""gen_escrow.py — escrow twins: emits lisp + TS from ONE op table.

Ops transcribed 1:1 from afp-clmm/escrow/CLMM_Escrow.thy (apply_op).
Theory = law: each export mirrors one constructor. A guard the theory maps
to None aborts here -> state unchanged (abort rolls back = thy None).

Theorems executed by the scenario asserts (net-zero-delta, phase 3):
  reachable_conservation  balance == in - out  in EVERY reachable state
  one_op_ok               every op preserves escrow_ok (guards are the ops)
Wire keys + export names are wire format — do NOT rename (port law):
  e:bal:<acct> | e:reserve | e:in | e:out
  deposit withdraw swap_in swap_out ft_on_transfer (+ views)

Usage: gen_escrow.py [out-root]   (default: repo port/ dir)
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_ROOT = os.path.dirname(HERE)  # port/
ESCROW_ACCT = "escrow.clmm.test.near"
FT_ACCT = "ft.clmm.test.near"
THEY = "afp-clmm/escrow/CLMM_Escrow.thy"

# ------------------------------------------------------------------ op table
# (name, thy-constructor, guard, ledger effect) — keep aligned with .thy
OPS = [
    ("deposit",  "Deposit u a",  "0 < a",                "bal[u]+=a; in+=a"),
    ("withdraw", "Withdraw u a", "0 < a & a <= bal[u]",  "bal[u]-=a; out+=a"),
    ("swap_in",  "SwapIn u a",   "0 < a & a <= bal[u]",  "bal[u]-=a; reserve+=a"),
    ("swap_out", "SwapOut u a",  "0 < a & a <= reserve", "reserve-=a; bal[u]+=a"),
]

HELPERS_LISP = """(define (sput k v) (near/storage_set k v))
(define (sget k d) (default (near/storage_get k) d))
(define (fail m) (near/log m) (near/abort m))
(define (add a b) (u128/add a b))
(define (sub a b) (u128/sub a b))
(define (ult a b) (u128/lt a b))
(define (bal u) (sget (str-cat "e:bal:" u) "0"))
(define (credit u a) (sput (str-cat "e:bal:" u) (add (bal u) a)))
(define (debit u a)
  (if (ult (bal u) a) (fail "ERR_FUNDS") "ok")
  (sput (str-cat "e:bal:" u) (sub (bal u) a)))"""

HELPERS_TS = """function sget(k: string): string {
  return near.storageGet(k) ?? "0";
}
function sput(k: string, v: string): void {
  near.storageSet(k, v);
}
function fail(m: string): void {
  near.log(m);
  near.abort(m);
}
function bal(u: string): string {
  return sget("e:bal:" + u);
}
function credit(u: string, a: string): void {
  sput("e:bal:" + u, u128.add(bal(u), a));
}
function debit(u: string, a: string): void {
  if (u128.lt(bal(u), a)) fail("ERR_FUNDS");
  sput("e:bal:" + u, u128.sub(bal(u), a));
}"""


def lisp_src():
    return f''';; escrow: NEP-141 custody shell (CLMM_Escrow.thy port). Generated by
;; gen_escrow.py — edit the generator, not this file; every name regenerates.
;; Theory: afp-clmm/escrow/CLMM_Escrow.thy (apply_op = law). A guard the
;; theory maps to None aborts here: state unchanged (abort rolls back).
;; Executed theorem: reachable_conservation — after every step,
;;   sum(e:bal:*) + e:reserve == e:in - e:out   (no hypotheses).
;; Keys ("e:...") are wire format — do NOT rename.
{HELPERS_LISP}

;; theory Deposit u a (guard 0 < a): single-hop credit, caller attaches.
(define (deposit)
  (let* ((acct (default (near/json_get_str "account") ""))
         (u (if (= acct "") (near/predecessor_account_id) acct))
         (a (near/attached_deposit_u128)))
    (begin
      (if (u128/eq a "0") (fail "ERR_ZERO") "ok")
      (credit u a)
      (sput "e:in" (add (sget "e:in" "0") a))
      (near/log (str-cat "deposit u=" (str-cat u (str-cat " a=" a))))
      (near/return (bal u)))))

;; NEP-141 receiver (two-hop deposit): predecessor = token contract,
;; msg = credited account (falls back to tx signer). amount > 0 is the
;; theory guard; returning "0" = keep the full attached amount.
(define (ft_on_transfer)
  (let* ((a (default (near/json_get_str "amount") "0"))
         (msg (default (near/json_get_str "msg") ""))
         (u (if (= msg "") (near/predecessor_account_id) msg)))
    (begin
      (if (u128/eq a "0") (fail "ERR_ZERO") "ok")
      (credit u a)
      (sput "e:in" (add (sget "e:in" "0") a))
      (near/log (str-cat "ft_credit u=" (str-cat u (str-cat " a=" a))))
      (near/return "0"))))

;; theory Withdraw u a (guard 0 < a & a <= bal[u]). a is a LEDGER argument
;; (mirrors .thy) — not an attach; attaching here would add untracked value
;; and break reachable_conservation. Token payout is the ft-probe layer.
(define (withdraw)
  (let* ((a (default (near/json_get_str "amount") "0"))
         (u (near/predecessor_account_id)))
    (begin
      (if (u128/eq a "0") (fail "ERR_ZERO") "ok")
      (debit u a)
      (sput "e:out" (add (sget "e:out" "0") a))
      (near/log (str-cat "withdraw u=" (str-cat u (str-cat " a=" a))))
      (near/return a))))

;; theory SwapIn u a (guard 0 < a & a <= bal[u]): user credits become
;; reserve. a from args — no attach (credits are internal custody).
(define (swap_in)
  (let* ((a (default (near/json_get_str "amount") "0"))
         (u (near/predecessor_account_id)))
    (begin
      (if (u128/eq a "0") (fail "ERR_ZERO") "ok")
      (debit u a)
      (sput "e:reserve" (add (sget "e:reserve" "0") a))
      (near/return (sget "e:reserve" "0")))))

;; theory SwapOut u a (guard 0 < a & a <= reserve): reserve becomes user
;; credits (swap output stays IN custody — outflow only moves on withdraw).
(define (swap_out)
  (let* ((a (default (near/json_get_str "amount") "0"))
         (u (near/predecessor_account_id)))
    (begin
      (if (u128/eq a "0") (fail "ERR_ZERO") "ok")
      (if (ult (sget "e:reserve" "0") a) (fail "ERR_RESERVE") "ok")
      (sput "e:reserve" (sub (sget "e:reserve" "0") a))
      (credit u a)
      (near/return (bal u)))))

;; views: storage ground truth for scenario asserts (paid:/left: convention).
(define (get_balance) (near/return (bal (near/predecessor_account_id))))
(define (get_balance_of)
  (near/return (bal (default (near/json_get_str "account") ""))))
(define (get_reserve) (near/return (sget "e:reserve" "0")))
(define (get_inflow) (near/return (sget "e:in" "0")))
(define (get_outflow) (near/return (sget "e:out" "0")))

(export "deposit" deposit)
(export "ft_on_transfer" ft_on_transfer)
(export "withdraw" withdraw)
(export "swap_in" swap_in)
(export "swap_out" swap_out)
(export "get_balance" get_balance)
(export "get_balance_of" get_balance_of)
(export "get_reserve" get_reserve)
(export "get_inflow" get_inflow)
(export "get_outflow" get_outflow)
'''


def ts_src():
    return f'''// escrow TS twin (generated by gen_escrow.py). Edit the generator, not
// this file. Theory: afp-clmm/escrow/CLMM_Escrow.thy (apply_op = law);
// guard -> None aborts here, state unchanged. Keys ("e:...") are wire
// format — do NOT rename.
{HELPERS_TS}

// theory Deposit u a (guard 0 < a)
export function deposit(): string {{
  const acct = near.jsonGetStr("account") ?? "";
  const a = near.attachedDepositU128();
  const u = acct === "" ? near.predecessorAccountId() : acct;
  if (a === "0") fail("ERR_ZERO");
  credit(u, a);
  sput("e:in", u128.add(sget("e:in"), a));
  near.log("deposit u=" + u + " a=" + a);
  return bal(u);
}}

// NEP-141 receiver (two-hop deposit); returns "0" = keep the attached amount
export function ft_on_transfer(): string {{
  const a = near.jsonGetStr("amount") ?? "0";
  const msg = near.jsonGetStr("msg") ?? "";
  const u = msg === "" ? near.predecessorAccountId() : msg;
  if (a === "0") fail("ERR_ZERO");
  credit(u, a);
  sput("e:in", u128.add(sget("e:in"), a));
  near.log("ft_credit u=" + u + " a=" + a);
  return "0";
}}

// theory Withdraw u a (guard 0 < a & a <= bal[u]). a is a LEDGER argument
// (mirrors .thy) — not an attach; attaching here would add untracked value
// and break reachable_conservation.
export function withdraw(): string {{
  const a = near.jsonGetStr("amount") ?? "0";
  const u = near.predecessorAccountId();
  if (a === "0") fail("ERR_ZERO");
  debit(u, a);
  sput("e:out", u128.add(sget("e:out"), a));
  near.log("withdraw u=" + u + " a=" + a);
  return a;
}}

// theory SwapIn u a (guard 0 < a & a <= bal[u]): credits become reserve
export function swap_in(): string {{
  const a = near.jsonGetStr("amount") ?? "0";
  const u = near.predecessorAccountId();
  if (a === "0") fail("ERR_ZERO");
  debit(u, a);
  sput("e:reserve", u128.add(sget("e:reserve"), a));
  return sget("e:reserve");
}}

// theory SwapOut u a (guard 0 < a & a <= reserve)
export function swap_out(): string {{
  const a = near.jsonGetStr("amount") ?? "0";
  const u = near.predecessorAccountId();
  if (a === "0") fail("ERR_ZERO");
  if (u128.lt(sget("e:reserve"), a)) fail("ERR_RESERVE");
  sput("e:reserve", u128.sub(sget("e:reserve"), a));
  credit(u, a);
  return bal(u);
}}

export function get_balance(): string {{ return bal(near.predecessorAccountId()); }}
export function get_balance_of(): string {{
  const acct = near.jsonGetStr("account") ?? "";
  return bal(acct);
}}
export function get_reserve(): string {{ return sget("e:reserve"); }}
export function get_inflow(): string {{ return sget("e:in"); }}
export function get_outflow(): string {{ return sget("e:out"); }}
'''


def write(path, src):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(src)
    print(f"wrote {path} ({len(src)} B)")


def near_json(name, src, out):
    return json.dumps({"name": name, "src": src, "account": ESCROW_ACCT,
                       "network": "local", "output": out}, indent=1) + "\n"


def main():
    root = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_ROOT
    # paths.py layout: contracts/<group>/<dirname>/ (src/ + colocated ts/)
    base = os.path.join(root, "contracts", "escrow", "escrow")
    write(os.path.join(base, "src", "main.lisp"), lisp_src())
    write(os.path.join(base, "ts", "main.ts"), ts_src())
    nj = near_json("escrow", "src/main.lisp", "target/escrow.wasm")
    with open(os.path.join(base, "near.json"), "w") as f:
        f.write(nj)
    print(f"wrote {os.path.join(base, 'near.json')}")
    with open(os.path.join(base, "ts", "near.json"), "w") as f:
        f.write(json.dumps({"name": "escrow-ts", "src": "main.ts",
                            "output": "target/escrow-ts.wasm"}) + "\n")
    print(f"wrote {os.path.join(base, 'ts', 'near.json')}")


if __name__ == "__main__":
    main()
